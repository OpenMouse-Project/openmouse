// ── Supported Devices Data ────────────────────────────────────────────────
//
// Source of truth for statuses is the driver registry in `@openmouse/protocol`
// (`src/drivers/registry.ts`). Keep the statuses below in sync with it:
//
//   supported  — a driver in `@openmouse/protocol` covers the device (and, for
//                the ones with a `pids` field, those PIDs exist in the
//                protocol registry). Verified hardware reports are preferred.
//   pr         — a pull request that adds the driver is open.
//   quickwin   — the protocol is implemented; only a PID/config entry is
//                missing (a small addition to the existing driver).
//   likely     — a driver exists that probably covers the model, but the exact
//                PID/interface has not been confirmed on hardware.
//   driver     — no driver exists; the protocol is not implemented.
//   unknown    — nothing is known about the protocol.
//   pending    — a live community request from the support catalog. Not part
//                of the static table; `src/supported-live.ts` adds these at
//                runtime.
//
// `src/supported-mice.test.ts` re-checks every `supported`/`quickwin` claim and
// every PID against the protocol package so this table cannot silently drift
// from the code again. `src/supported-live.ts` additionally overlays live
// request counts and registry-listed supported models at runtime.

export type Status = "supported" | "pr" | "quickwin" | "likely" | "driver" | "unknown" | "pending";

export interface Mouse {
  brand: string;
  model: string;
  status: Status;
  /** Request votes. `pending` rows and matches against the live catalog are
   *  overlaid at runtime; otherwise this is the last-known baseline. */
  req: number;
  note: string;
  /** Known product IDs, where the protocol pins them (checked by tests). */
  pids?: readonly number[];
}

